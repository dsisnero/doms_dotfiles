# ssh setting
if node[:is_wsl]
  cmds = [
    "cp -r /mnt/c/.ssh/* #{home}/.ssh/",
    "chown #{user}:#{group} #{home}/.ssh/*",
    "find #{home}/.ssh -type f | xargs chmod 600",
    "find #{home}/.ssh -type d | xargs chmod 700"
  ]

  cmds.each do |cmd|
    user user
    execute cmd do
      only_if "test -d /mnt/c/.ssh"
    end
  end
end

